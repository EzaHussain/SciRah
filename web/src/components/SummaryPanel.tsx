"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { api, API_URL, ApiError } from "@/lib/api";
import { AI_DISCLAIMER, langInfo, SUMMARY_LANGS, type SummaryLang } from "@/lib/languages";
import type { Summary } from "@/lib/types";
import { useAuth } from "./AuthProvider";
import { PauseIcon, PlayIcon, SparkIcon, SpinnerIcon } from "./icons";
import { ShareMenu } from "./ShareMenu";

const textFor = (s: Summary | null, lang: SummaryLang) => (!s ? undefined : lang === "en" ? s.summaryEn : s.translations?.[lang]);

export function SummaryPanel({
  paperId,
  title,
  hasAbstract,
  isOpenAccess,
}: {
  paperId: string;
  title: string;
  hasAbstract: boolean;
  isOpenAccess: boolean;
}) {
  const { user, getToken, configured } = useAuth();
  const pathname = usePathname();
  const [summary, setSummary] = useState<Summary | null>(null);
  const [checking, setChecking] = useState(true);
  const [busy, setBusy] = useState<null | "summary" | SummaryLang>(null);
  const [error, setError] = useState<string | null>(null);
  const [lang, setLang] = useState<SummaryLang>("en");

  useEffect(() => {
    let cancelled = false;
    api<Summary | null>(`/ai/summary?paperId=${encodeURIComponent(paperId)}`)
      .then((s) => !cancelled && setSummary(s))
      .catch(() => undefined)
      .finally(() => !cancelled && setChecking(false));
    return () => {
      cancelled = true;
    };
  }, [paperId]);

  const generate = async () => {
    setError(null);
    setBusy("summary");
    try {
      setSummary(await api<Summary>("/ai/summary", { method: "POST", token: await getToken(), body: { paperId } }));
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Something went wrong. Please try again.");
    } finally {
      setBusy(null);
    }
  };

  const chooseLang = async (l: SummaryLang) => {
    setError(null);
    if (l === "en" || textFor(summary, l)) return setLang(l);
    if (!user) {
      setLang(l);
      return;
    }
    setBusy(l);
    try {
      const res = await api<Summary>("/ai/translate", { method: "POST", token: await getToken(), body: { paperId, lang: l } });
      setSummary(res);
      setLang(l);
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Translation failed. Please try again.");
    } finally {
      setBusy(null);
    }
  };

  const canSummarise = hasAbstract || isOpenAccess;
  const text = textFor(summary, lang);
  const info = langInfo(lang);
  const signInHref = `/login?next=${encodeURIComponent(pathname)}`;

  return (
    <section aria-labelledby="ai-summary" className="card relative overflow-hidden p-5 sm:p-6">
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <h2 id="ai-summary" className="flex items-center gap-2 text-lg font-semibold">
          <SparkIcon className="h-5 w-5 text-primary" /> Plain-language summary
        </h2>
      </div>

      {summary && (
        <div role="radiogroup" aria-label="Summary language" className="-mx-1 mb-4 flex gap-1.5 overflow-x-auto px-1 pb-1">
          {SUMMARY_LANGS.map((l) => (
            <button
              key={l.code}
              role="radio"
              aria-checked={lang === l.code}
              title={l.label}
              disabled={busy !== null}
              onClick={() => chooseLang(l.code)}
              className={`flex shrink-0 items-center gap-1.5 rounded-full border px-3 py-1 text-sm transition-colors ${
                lang === l.code ? "border-primary bg-primary/15 font-medium text-fg" : "border-line text-muted hover:border-primary/50 hover:text-fg"
              }`}
            >
              {busy === l.code && <SpinnerIcon className="h-3.5 w-3.5" />}
              <span lang={l.code} className={l.code === "ur" ? "font-urdu text-[0.95rem] leading-none" : ""}>
                {l.native}
              </span>
            </button>
          ))}
        </div>
      )}

      {checking ? (
        <div className="space-y-2">
          <div className="skeleton h-3.5 w-full" />
          <div className="skeleton h-3.5 w-11/12" />
          <div className="skeleton h-3.5 w-3/4" />
        </div>
      ) : summary && text ? (
        <>
          <p
            lang={info.code}
            dir={info.dir}
            className={`max-w-[70ch] text-fg ${lang === "ur" ? "urdu" : lang === "ar" ? "text-[1.08rem] leading-loose" : "leading-relaxed"}`}
          >
            {text}
          </p>
          <AiDisclaimer extra={`Generated by ${summary.model} from the ${summary.basis === "fulltext" ? "open-access full text" : "abstract"}.`} />
          <div className="mt-4 flex flex-wrap items-center gap-2">
            {user && <VoiceOver key={lang} paperId={paperId} lang={lang} text={text} />}
            <ShareMenu
              path={`/paper/${encodeURIComponent(paperId)}`}
              title={title}
              text={`${text}\n\n(AI-generated summary via SciRah — may contain mistakes.)`}
              buttonLabel="Share summary"
              className="btn-ghost py-1.5"
            />
            <Link href={`/paper/${encodeURIComponent(paperId)}/slide?lang=${lang}`} className="btn-ghost py-1.5">
              <SlideIcon /> One-slide summary
            </Link>
          </div>
        </>
      ) : summary && !text ? (
        <div className="flex flex-wrap items-center gap-3">
          <p className="text-sm text-muted">The {info.label} version hasn’t been created yet.</p>
          {user ? (
            <button className="btn-primary" onClick={() => chooseLang(lang)} disabled={busy !== null}>
              {busy === lang ? <SpinnerIcon /> : <SparkIcon />} Translate to {info.label}
            </button>
          ) : (
            <Link href={signInHref} className="btn-primary">
              Sign in to translate
            </Link>
          )}
        </div>
      ) : !canSummarise ? (
        <p className="text-sm text-muted">This paper has no abstract or open-access text available, so it can’t be summarised.</p>
      ) : !configured ? (
        <p className="text-sm text-muted">Sign-in is not configured on this server.</p>
      ) : !user ? (
        <div className="flex flex-wrap items-center gap-3">
          <p className="text-sm text-muted">Get a 3–5 sentence explanation of this paper in English, Urdu, Hindi, Arabic, Chinese, French or Spanish.</p>
          <Link href={signInHref} className="btn-primary">
            Sign in to summarise
          </Link>
        </div>
      ) : (
        <div className="flex flex-wrap items-center gap-3">
          <p className="text-sm text-muted">Get a 3–5 sentence explanation of this paper, with translations into 6 languages and a voice-over.</p>
          <button className="btn-primary" disabled={busy !== null} onClick={generate}>
            {busy === "summary" ? (
              <>
                <SpinnerIcon /> Summarising…
              </>
            ) : (
              <>
                <SparkIcon /> Generate summary
              </>
            )}
          </button>
        </div>
      )}

      {error && (
        <p role="alert" className="mt-3 text-sm text-accent">
          {error}
        </p>
      )}
    </section>
  );
}

/** The notice shown under every AI summary / translation. */
export function AiDisclaimer({ extra }: { extra?: string }) {
  return (
    <p className="mt-4 flex gap-2 rounded-xl border border-accent/30 bg-accent/8 px-3 py-2 text-xs leading-relaxed text-fg/80">
      <span aria-hidden="true" className="mt-px font-semibold text-accent">
        !
      </span>
      <span>
        {AI_DISCLAIMER}
        {extra && <span className="text-muted"> {extra}</span>}
      </span>
    </p>
  );
}

const SlideIcon = () => (
  <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.9} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" className="h-4 w-4">
    <rect x="3" y="4" width="18" height="13" rx="2" />
    <path d="M8 21h8M12 17v4M7 9h6M7 12h10" />
  </svg>
);

/** Pick the browser's best installed voice for a language (used when server voice-over is unavailable). */
function browserVoice(lang: SummaryLang): SpeechSynthesisVoice | null {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return null;
  const voices = window.speechSynthesis.getVoices();
  const prefix = langInfo(lang).bcp47.split("-")[0].toLowerCase();
  const matches = voices.filter((v) => v.lang.toLowerCase().replace("_", "-").startsWith(prefix));
  // Prefer the higher-quality "Natural"/"Online"/Google voices when present.
  return matches.find((v) => /natural|online|google/i.test(v.name)) ?? matches[0] ?? null;
}

/**
 * Voice-over for the summary in the current language. Uses the server (OpenAI text-to-speech) when
 * available, and falls back to the browser's built-in speech synthesis — free and works offline.
 */
function VoiceOver({ paperId, lang, text }: { paperId: string; lang: SummaryLang; text: string }) {
  const { getToken } = useAuth();
  const audioRef = useRef<HTMLAudioElement | null>(null);
  const urls = useRef<Partial<Record<SummaryLang, string>>>({});
  const [state, setState] = useState<"idle" | "loading" | "playing" | "paused">("idle");
  const [engine, setEngine] = useState<"server" | "browser">("server");
  const [error, setError] = useState<string | null>(null);

  // The parent remounts this per language (key={lang}), so unmount also stops playback on a switch.
  useEffect(() => {
    const cache = urls.current;
    return () => {
      audioRef.current?.pause();
      if (typeof window !== "undefined" && "speechSynthesis" in window) window.speechSynthesis.cancel();
      Object.values(cache).forEach((u) => u && URL.revokeObjectURL(u));
    };
  }, []);

  const speakInBrowser = async () => {
    if (!("speechSynthesis" in window)) throw new Error("Voice-over isn’t available in this browser.");
    const synth = window.speechSynthesis;
    // Voices load asynchronously in some browsers.
    if (!synth.getVoices().length) await new Promise((r) => setTimeout(r, 300));
    const voice = browserVoice(lang);
    if (!voice && lang !== "en")
      throw new Error(`No ${langInfo(lang).label} voice is installed in this browser. Try Microsoft Edge, or add one in your system’s speech settings.`);
    synth.cancel();
    const u = new SpeechSynthesisUtterance(text);
    if (voice) u.voice = voice;
    u.lang = voice?.lang ?? langInfo(lang).bcp47;
    u.rate = 0.95;
    u.onstart = () => setState("playing");
    u.onend = () => setState("idle");
    u.onerror = () => setState("idle");
    setEngine("browser");
    synth.speak(u);
  };

  const toggle = async () => {
    setError(null);
    if (engine === "browser" && (state === "playing" || state === "paused")) {
      const synth = window.speechSynthesis;
      if (state === "playing") {
        synth.pause();
        setState("paused");
      } else {
        synth.resume();
        setState("playing");
      }
      return;
    }
    const audio = audioRef.current;
    if (state === "playing") {
      audio?.pause();
      return;
    }
    if (state === "paused" && audio) {
      await audio.play();
      return;
    }
    setState("loading");
    try {
      let url = urls.current[lang];
      if (!url && engine === "server") {
        const token = await getToken();
        const res = await fetch(`${API_URL}/ai/tts?paperId=${encodeURIComponent(paperId)}&lang=${lang}`, {
          headers: token ? { Authorization: `Bearer ${token}` } : {},
        }).catch(() => null);
        if (res?.ok) {
          url = URL.createObjectURL(await res.blob());
          urls.current[lang] = url;
        } else if (res?.status === 429) {
          const data = await res.json().catch(() => ({}));
          throw new Error(data.message ?? "Daily limit reached");
        }
      }
      if (!url) {
        // Server voice-over unavailable (not configured, or failed): use the browser's own voice.
        await speakInBrowser();
        return;
      }
      const el = new Audio(url);
      el.onplay = () => setState("playing");
      el.onpause = () => setState(el.ended ? "idle" : "paused");
      el.onended = () => setState("idle");
      audioRef.current = el;
      await el.play();
    } catch (e) {
      setError((e as Error).message);
      setState("idle");
    }
  };

  return (
    <div className="flex items-center gap-2">
      <button className="btn-primary py-1.5" onClick={toggle} disabled={state === "loading"} aria-label={state === "playing" ? "Pause voice-over" : "Listen to summary"}>
        {state === "loading" ? <SpinnerIcon /> : state === "playing" ? <PauseIcon /> : <PlayIcon />}
        {state === "playing" ? "Pause" : "Listen"}
      </button>
      {engine === "browser" && !error && <span className="text-[11px] text-muted">browser voice</span>}
      {error && <span className="max-w-xs text-xs text-accent">{error}</span>}
    </div>
  );
}
